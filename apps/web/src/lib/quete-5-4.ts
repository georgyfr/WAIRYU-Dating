/** Likert 1-5 → 0-1 (inversées recodées 6 − r — Arbitrage 1). */
function contribution(reponse: number, orient: 'D' | 'I'): number {
  return ((orient === 'D' ? reponse : 6 - reponse) - 1) / 4;
}

export interface Score54 {
  /** La position tenue — moyenne des 3 items de la posture (AFF_D côté
   *  moteur), normalisée 0-1 (haut = la posture dominante chez toi). */
  affirmation: number;
  /** La solution qui garde les deux — idem (COOP_D côté moteur). */
  cooperation: number;
  /** Le milieu qui débloque — idem (COMP_D côté moteur). */
  compromis: number;
  /** Le sujet qu'on remet — idem (EVIT_D côté moteur). */
  evitement: number;
  /** La place laissée à l'autre — idem (CED_D côté moteur). */
  cession: number;
  /** Signature d'index (contrat du registre : Record<string, number>) —
   *  y entrent aussi les contributions recodées des 5 pivots (clés
   *  « pivot_… » — moteur du départage, JAMAIS rendues). */
  [dim: string]: number;
}

/**
 * Scorer du Livrable : cinq scores de posture (moyennes des contributions
 * recodées, 3 items par posture), normalisés 0-1. Ils alimentent la cascade
 * SIG-5.4-01 (choisirVariante + cascade54) et la carte (canal carte).
 *
 * Les 8▲ trames (JR1/SD) n'entrent dans AUCUN score affiché — dimension
 * null au 02, aucune entrée dans ITEMS : elles ne franchissent jamais cette
 * fonction (aucune restitution — verrou capital). SIG-5.4-02 (matrice de
 * viabilité, cellules affirmer×affirmer / coopérer×coopérer gelées mission)
 * : MOTEUR SEUL — JAMAIS au rendu, jamais au match affiché, non calculée
 * ici. SIG-5.4-03 (côté 5.1 × JR1) : ATTENDU, non calculé (opère au portrait
 * de domaine du Cœur). SIG-5.4-04 (vigilance 2+ SD) : MOTEUR SEUL, non
 * calculé ici — libellé de la charte seul s'il sort un jour.
 */
export function scorer(reponses: Record<string, number>): Score54 {
  const parPosture = new Map<string, { total: number; n: number }>();
  const pivots: Record<string, number> = {};
  for (const code of PASSATION) {
    const it = PAR_CODE.get(code);
    const r = it ? reponses[it.code] : undefined;
    if (it && typeof r === 'number' && r >= 1 && r <= 5) {
      const c = contribution(r, it.orient);
      const bloc = parPosture.get(it.dim) ?? { total: 0, n: 0 };
      bloc.total += c;
      bloc.n += 1;
      parPosture.set(it.dim, bloc);
      if (PIVOTS.has(it.code)) pivots[`pivot_${it.dim}`] = c;
    }
  }
  const posture = (dim: string): number => {
    const bloc = parPosture.get(dim);
    return bloc && bloc.n > 0 ? bloc.total / bloc.n : 0;
  };
  return {
    affirmation: posture('affirmation'),
    cooperation: posture('cooperation'),
    compromis: posture('compromis'),
    evitement: posture('evitement'),
    cession: posture('cession'),
    ...pivots,
  };
}

/** Les 7 variantes — ids VERBATIM (cartes.yaml, ordre du sélecteur 1 → 7) :
 *  5 postures dominantes + le profil mixte (DUO) + le profil égalitaire
 *  (EQUILIBRE) — partition exclusive + exhaustive (C6). */
export type VarianteId54 =
  | 'CARTE-5.4-GOUVERNAIL'
  | 'CARTE-5.4-ATELIER'
  | 'CARTE-5.4-PASSERELLE'
  | 'CARTE-5.4-PAUSE'
  | 'CARTE-5.4-PASSAGE'
  | 'CARTE-5.4-DUO'
  | 'CARTE-5.4-EQUILIBRE';

/** Clé de posture — sans accent, cohérente partout (items, score, cascade). */
export type ClePosture54 = 'affirmation' | 'cooperation' | 'compromis' | 'evitement' | 'cession';

/** La table des postures — carte du dominant et 1ʳᵉ position de passation
 *  (cascade SIG-5.4-01 ; 1ʳᵉs positions réelles du mélange 254427 :
 *  éviter 1 · céder 3 · compromettre 4 · affirmer 10 · coopérer 12). */
const POSTURES: readonly {
  dim: ClePosture54;
  carte: VarianteId54;
  pos1: number;
}[] = [
  { dim: 'affirmation', carte: 'CARTE-5.4-GOUVERNAIL', pos1: 10 },
  { dim: 'cooperation', carte: 'CARTE-5.4-ATELIER', pos1: 12 },
  { dim: 'compromis', carte: 'CARTE-5.4-PASSERELLE', pos1: 4 },
  { dim: 'evitement', carte: 'CARTE-5.4-PAUSE', pos1: 1 },
  { dim: 'cession', carte: 'CARTE-5.4-PASSAGE', pos1: 3 },
];

const valeurPosture = (score: Score54, cle: ClePosture54): number =>
  typeof score[cle] === 'number' ? (score[cle] as number) : 0;

/** Le duel de tête du 07 §0 : meneuse/nuance = les deux postures au sommet.
 *  Parcours en ordre de 1ʳᵉ position de passation (l'égalité exacte de scores
 *  revient donc à la posture vue le plus tôt) ; quasi-égalité (écart < 0.05)
 *  → départage par le pivot le mieux noté des deux postures, puis, à
 *  égalité exacte de pivots (ou pivot absent — repli déterministe), par la
 *  1ʳᵉ position de passation (précédents 5.1/5.3/5.7). Le départage ordonne
 *  le récit (qui mène, qui nuance) — il ne change pas le profil. */
function duelDeTete(score: Score54): {
  meneuse: ClePosture54;
  nuance: ClePosture54;
  ecart: number;
  departage: 'pivot' | 'position' | null;
} {
  const ordo = [...POSTURES]
    .map((p) => ({ dim: p.dim, pos1: p.pos1, v: valeurPosture(score, p.dim) }))
    .sort((a, b) => a.pos1 - b.pos1);
  let meneuse = ordo[0];
  let nuance = ordo[1];
  for (const cand of ordo.slice(1)) {
    if (cand.v > meneuse.v) {
      nuance = meneuse;
      meneuse = cand;
    } else if (cand !== nuance && cand.v > nuance.v) {
      nuance = cand;
    }
  }
  let departage: 'pivot' | 'position' | null = null;
  const ecartBrut = meneuse.v - nuance.v;
  if (ecartBrut < 0.05) {
    const p1 = score[`pivot_${meneuse.dim}`];
    const p2 = score[`pivot_${nuance.dim}`];
    if (typeof p1 === 'number' && typeof p2 === 'number' && p1 !== p2) {
      departage = 'pivot';
      if (p1 < p2) {
        const t = meneuse;
        meneuse = nuance;
        nuance = t;
      }
    } else {
      // Pivots à égalité exacte (ou absents — repli déterministe) : la 1ʳᵉ
      // position de passation tranche/confirme l'ordre du récit.
      departage = 'position';
      if (nuance.pos1 < meneuse.pos1) {
        const t = meneuse;
        meneuse = nuance;
        nuance = t;
      }
    }
  }
  return {
    meneuse: meneuse.dim,
    nuance: nuance.dim,
    ecart: Math.abs(meneuse.v - nuance.v),
    departage,
  };
}

/**
 * Sélecteur VERBATIM (07-miroir §0 + cartes.yaml — cascade SIG-5.4-01,
 * partition exclusive + exhaustive des 7 profils, C6 ; ordre 1 → 7) :
 *  1. étendue des cinq scores ≤ 0.10 → CARTE-5.4-EQUILIBRE (profil
 *     égalitaire) — « l'étendue prime sur la bande » au bord ;
 *  2. sinon dominante = max des cinq → si la 2ᵉ posture est à ≤ 0.10 de la
 *     1ʳᵉ → CARTE-5.4-DUO (profil mixte — deux postures dominantes serrées :
 *     la 1ʳᵉ mène, la 2ᵉ nuance ; la meneuse est nommée par le départage) ;
 *  3. au-delà de 0.10 → la carte de la posture dominante seule (GOUVERNAIL /
 *     ATELIER / PASSERELLE / PAUSE / PASSAGE — secondaire discret, une
 *     phrase au portrait de domaine).
 * Quasi-égalité (écart 1ᵉʳ-2ᵉ < 0.05) → départage au pivot puis à la 1ʳᵉ
 * position de passation — le départage ordonne le récit, il ne change pas le
 * profil (un écart < 0.05 reste dans la bande 0.10 → DUO). Bornes 0.05 /
 * bande 0.10 / étendue 0.10 : provisoires concepteur (« À VALIDER PAR LE
 * COMITÉ », re-signature professionnelle avant bêta) — métadonnées moteur,
 * jamais rendues. La matrice de viabilité (SIG-5.4-02) et les signaux des
 * 8▲ (SIG-5.4-03/04) ne participent JAMAIS à la sélection ni au rendu.
 */
export function choisirVariante(score: Score54): VarianteId54 {
  const valeurs = POSTURES.map((p) => valeurPosture(score, p.dim));
  const etendue = Math.max(...valeurs) - Math.min(...valeurs);
  if (etendue <= 0.1) return 'CARTE-5.4-EQUILIBRE';
  const { meneuse, ecart } = duelDeTete(score);
  if (ecart <= 0.1) return 'CARTE-5.4-DUO';
  const dominante = POSTURES.find((p) => p.dim === meneuse);
  return dominante ? dominante.carte : 'CARTE-5.4-EQUILIBRE';
}

/** La cascade SIG-5.4-01 rendue CALCULABLE (07 §0) pour la couche miroir —
 *  aucun de ces champs ne franchit la carte : 'egalitaire' = palette entière
 *  (aucune citation d'énoncé — des scores serrés ne prouvent aucun accord
 *  haut individualisé, précédent 5.1 MIXTE) ; 'mixte' = le duo (la meneuse
 *  cite son énoncé D, la nuance raconte sans citation supplémentaire) ;
 *  'dominante' = la posture seule (secondaire discret). departage : le
 *  mécanisme qui a nommé la meneuse (null = l'ordre strict des scores). */
export interface Cascade54 {
  mode: 'egalitaire' | 'mixte' | 'dominante';
  meneuse: ClePosture54;
  nuance: ClePosture54;
  departage: 'pivot' | 'position' | null;
  etendue: number;
}

export function cascade54(score: Score54): Cascade54 {
  const valeurs = POSTURES.map((p) => valeurPosture(score, p.dim));
  const etendue = Math.max(...valeurs) - Math.min(...valeurs);
  const duel = duelDeTete(score);
  if (etendue <= 0.1) {
    return { mode: 'egalitaire', meneuse: duel.meneuse, nuance: duel.nuance, departage: null, etendue };
  }
  return {
    mode: duel.ecart <= 0.1 ? 'mixte' : 'dominante',
    meneuse: duel.meneuse,
    nuance: duel.nuance,
    departage: duel.departage,
    etendue,
  };
}

